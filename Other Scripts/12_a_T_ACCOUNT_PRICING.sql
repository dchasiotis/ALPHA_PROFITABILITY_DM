SELECT
      DIM_REF_PERIOD.HMNIA HMNIA
    , acc.ENTITY_CODE ENTITY_CODE
    , acc.ACCOUNT_CODE ACCOUNT_CODE
    , acc.ACCOUNT_GL_ACCOUNT_TYPE_CODE ACCOUNT_GL_ACCOUNT_TYPE_CODE
   	, CASE WHEN a.EXPOSURE_EUR <> 0 and a.FLAG_RWA > 0 and abs(a.RWA_EUR/a.EXPOSURE_EUR) > 2 THEN 
	  CASE WHEN rwa_icap.COUNTERPARTY_ORIGINAL_CALC IS NOT NULL THEN ISNULL(rwa_icap.ERW_calc,0) 
		   WHEN rwa_icap.COUNTERPARTY_ORIGINAL_CALC IS NULL AND acc.ACCOUNT_MIS_PRODUCT_CODE in ('LEGU','LECR') THEN ISNULL(rwa_LG.RATIO_CALC, 0)
		   ELSE isnull(rwa.RATIO_CALC, 0)
	       END
	  WHEN a.EXPOSURE_EUR <> 0 and a.FLAG_RWA > 0 THEN a.RWA_EUR/a.EXPOSURE_EUR ELSE
      CASE WHEN rwa_icap.COUNTERPARTY_ORIGINAL_CALC IS NOT NULL THEN ISNULL(rwa_icap.ERW_calc,0) 
	  WHEN rwa_icap.COUNTERPARTY_ORIGINAL_CALC IS NULL AND acc.ACCOUNT_MIS_PRODUCT_CODE in ('LEGU','LECR') THEN ISNULL(rwa_LG.RATIO_CALC, 0)
	  ELSE isnull(rwa.RATIO_CALC, 0)
	   END END ACCOUNT_RTE_RWA
    , 0 ACCOUNT_RTE_ECL
FROM rep.FACT_CLIENT_REF_DATE DIM_REF_PERIOD, 
	rep.DIM_ACCOUNT acc 
	LEFT JOIN 
	(SELECT 
  	      fct.DIM_ACCOUNT_ID DIM_ACCOUNT_ID
	    , 1 FLAG_RWA
  	    , sum(fct.EOP_OFFBS_BALANCE_EUR) EXPOSURE_EUR
	    , sum(fct.EOP_ONBS_RWA_EUR)      RWA_EUR
	 FROM rep.FACT_CLIENT_REF_DATE DIM_REF_PERIOD, rep.FACT_CLIENT fct
  	 	LEFT JOIN rep.DIM_BALANCE_TYPE bt ON bt.DIM_BALANCE_TYPE_ID = fct.DIM_BALANCE_TYPE_ID
  	 	LEFT JOIN rep.DIM_GL_ACCOUNT_TYPE gl ON gl.DIM_GL_ACCOUNT_TYPE_ID = fct.DIM_GL_ACCOUNT_TYPE_ID
	 	LEFT JOIN rep.DIM_ENTITY ent ON ent.DIM_ENTITY_ID = fct.DIM_ENTITY_ID
  	 	LEFT JOIN rep.DIM_MIS_PRODUCT prd ON prd.DIM_MIS_PRODUCT_ID = fct.DIM_MIS_PRODUCT_ID
  	 WHERE fct.DIM_PERIOD_ID = (select distinct HMNIA from stg.X_RWAS_RATIO_V) 
	    and bt.BALANCE_TYPE_CODE = '901'
	    and gl.GL_ACCOUNT_TYPE_CODE = '1' 
	    and (ent.ENTITY_CODE <> 'AB1001' or (ent.ENTITY_CODE = 'AB1001' and prd.MIS_PRODUCT_CODE not in ('LEAS', 'FACT','FLEX')))
   	 GROUP BY fct.DIM_ACCOUNT_ID
  	) a ON a.DIM_ACCOUNT_ID = acc.DIM_ACCOUNT_ID 
	LEFT JOIN stg.X_RWAS_RATIO_V rwa ON acc.ACCOUNT_RISK_PRODUCT_CODE = rwa.ASSET_CLASS_CODE and acc.ENTITY_CODE = rwa.ENTITY_CODE_CALC and case when acc.ACCOUNT_EBA_FLAG_CODE in ('PL', 'FPL') then 'PE' else 'NPE' end = rwa.EBA_FLAG_CODE_CALC
	LEFT JOIN stg.X_RWAS_RATIO_LGs_LCs_V rwa_LG ON acc.ACCOUNT_RISK_PRODUCT_CODE = rwa_LG.ASSET_CLASS_CODE and acc.ENTITY_CODE = rwa_LG.ENTITY_CODE_CALC and case when acc.ACCOUNT_EBA_FLAG_CODE in ('PL', 'FPL') then 'PE' else 'NPE' end = rwa_LG.EBA_FLAG_CODE_CALC
	LEFT JOIN stg.X_RWA_ICAP_CDIS_V rwa_icap ON acc.ACCOUNT_CLIENT_CODE=rwa_icap.COUNTERPARTY_ORIGINAL_CALC and acc.ENTITY_CODE=rwa_icap.ENTITY_CODE_CALC

WHERE acc.ACCOUNT_GL_ACCOUNT_TYPE_CODE = '1' 
	and (acc.ENTITY_CODE <> 'AB1001' or (acc.ENTITY_CODE = 'AB1001' and acc.ACCOUNT_MIS_PRODUCT_CODE not in ('LEAS', 'FACT','FLEX')))


