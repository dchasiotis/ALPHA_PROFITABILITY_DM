	WHEN acc.ACCOUNT_FTP_DURATION > 366  and acc.ACCOUNT_FTP_DURATION <= 732  THEN RTE_12M+((acc.ACCOUNT_FTP_DURATION-366) *(RTE_02Y - RTE_12M)/366)
	WHEN acc.ACCOUNT_FTP_DURATION > 732  and acc.ACCOUNT_FTP_DURATION <= 1098 THEN RTE_02Y+((acc.ACCOUNT_FTP_DURATION-732) *(RTE_03Y - RTE_02Y)/366)
	WHEN acc.ACCOUNT_FTP_DURATION > 1098 and acc.ACCOUNT_FTP_DURATION <= 1830 THEN RTE_03Y+((acc.ACCOUNT_FTP_DURATION-1098)*(RTE_05Y - RTE_03Y)/732)
	WHEN acc.ACCOUNT_FTP_DURATION > 1830 and acc.ACCOUNT_FTP_DURATION <= 3660 THEN RTE_05Y+((acc.ACCOUNT_FTP_DURATION-1830)*(RTE_10Y - RTE_05Y)/1830)
