		AND fct.DIM_CURRENCY_FTP_ID = ftp_as.DIM_CURRENCY_FTP_ID
		AND drcf.FTP_RATE_TYPE_AS_ID = ftp_as.DIM_FTP_RATE_TYPE_ID

