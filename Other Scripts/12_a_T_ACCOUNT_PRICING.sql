	WHEN acc.ACCOUNT_FTP_DURATION > 30   and acc.ACCOUNT_FTP_DURATION <= 60   THEN RTE_01M+((acc.ACCOUNT_FTP_DURATION-30)  *(RTE_02M - RTE_01M)/30)
