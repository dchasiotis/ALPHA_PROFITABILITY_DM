	WHEN acc.ACCOUNT_FTP_DURATION > 5490 and acc.ACCOUNT_FTP_DURATION <= 7320  THEN RTE_15Y+((acc.ACCOUNT_FTP_DURATION-5490)*(RTE_20Y - RTE_15Y)/1830)
