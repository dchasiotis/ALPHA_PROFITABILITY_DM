	WHEN acc.ACCOUNT_FTP_DURATION > 180  and acc.ACCOUNT_FTP_DURATION <= 275  THEN RTE_06M+((acc.ACCOUNT_FTP_DURATION-180) *(RTE_09M - RTE_06M)/95)
