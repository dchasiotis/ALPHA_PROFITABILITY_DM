, CASE 
    WHEN acc.ACCOUNT_FTP_DURATION < 0    or  acc.ACCOUNT_FTP_DURATION is null THEN RTE_MFR                                                                                
    WHEN acc.ACCOUNT_FTP_DURATION = 0                                         THEN RTE_OVN
	WHEN acc.ACCOUNT_FTP_DURATION > 0    and acc.ACCOUNT_FTP_DURATION <= 7    THEN RTE_OVN+((acc.ACCOUNT_FTP_DURATION-0)   *(RTE_01W - RTE_OVN)/7)
