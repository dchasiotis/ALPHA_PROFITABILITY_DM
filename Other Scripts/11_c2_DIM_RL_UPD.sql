SELECT
'UPDATE MIS.REP.DIM_RL_CLIENT_FTP
  SET FTP_RATE_COMPONENTS_MAP_CODE = ''' + FTP_RATE_COMPONENTS_MAP_CODE + '''
  WHERE 1=1'
  + CASE WHEN FTP_PRODUCT_CODE IS NOT NULL THEN ' AND FTP_PRODUCT_CODE =''' + FTP_PRODUCT_CODE + '''' ELSE '' END
  + CASE WHEN FTP_AMOUNT_BUCKET_CODE IS NOT NULL THEN ' AND FTP_AMOUNT_BUCKET_CODE =''' + FTP_AMOUNT_BUCKET_CODE  + '''' ELSE ''  END
  + CASE WHEN FTP_MATURITY_BUCKET_CODE IS NOT NULL THEN ' AND FTP_MATURITY_BUCKET_CODE =''' + FTP_MATURITY_BUCKET_CODE  + '''' ELSE ''  END
  + ';'
FROM MIS.CLS.CLS_FTP_RATE_COMPONENTS_MAP;











