CREATE VIEW STG.X_COM_AXA_PAYMENTS_V
AS
SELECT 
    INSURANCE_PAYMENT_ID
,   ACCOUNT_ID 
,   ACCOUNT_CODE
,   SOURCE_SYSTEM_CODE
,   SOURCE_SYSTEM_NAME
,   PAYMENT_DATE
,   cast(CASE WHEN isnull(PAYMENT_DATE,'')  = '' THEN '9999-01-01' 
         ELSE PAYMENT_DATE END as date)  AS PAYMENT_DATE_CALC
,   PAYMENT_AMOUNT
,   round(convert(float,REPLACE(LTRIM(RTRIM(isnull(PAYMENT_AMOUNT,'0'))),',','.')),6)  
AS PAYMENT_AMOUNT_CALC
,   ACTUAL_PAYMENT_METHOD_CODE
,   ACTUAL_PAYMENT_METHOD_DESCRIPTION
,   CONNECTED_ACCOUNT_CODE
,   RECEIPT_NUMBER
,   EFFECTIVE_DATE
,   cast(CASE WHEN isnull(EFFECTIVE_DATE,'')  = '' THEN '9999-01-01' 
         ELSE EFFECTIVE_DATE END as date)  AS EFFECTIVE_DATE_CALC
,   END_DATE
,   cast(CASE WHEN isnull(END_DATE,'')  = '' THEN '9999-01-01' 
         ELSE END_DATE END as date)  AS END_DATE_CALC
,   REFERENCE_DATE
,   cast(CASE WHEN isnull(REFERENCE_DATE,'')  = '' THEN '9999-01-01' 
         ELSE REFERENCE_DATE END as date)  AS REFERENCE_DATE_CALC
,   NUMBER_OF_INSURANCE_PAYMENTS


	

FROM    OPENROWSET(BULK 'X:/DATA/Commissions/DATA/X_COM_AXA_PAYMENTS.csv', FORMATFILE = 'X:/DATA/Commissions/FF/X_COM_AXA_PAYMENTS_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz

