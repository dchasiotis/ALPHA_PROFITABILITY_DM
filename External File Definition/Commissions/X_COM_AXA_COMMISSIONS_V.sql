ALTER VIEW STG.X_COM_AXA_COMMISSIONS_V
AS
SELECT 
   REFERENCE_DATE
,   cast(CASE WHEN isnull(REFERENCE_DATE,'')  = '' THEN '9999-01-01' 
ELSE REFERENCE_DATE END as date)  AS REFERENCE_DATE_CALC
,  ON_BALANCE_GROSS_BANK_INSURANCE
,   round(convert(float,REPLACE(LTRIM(RTRIM(isnull(ON_BALANCE_GROSS_BANK_INSURANCE,'0'))),',','.')),6)  
AS ON_BALANCE_GROSS_BANK_INSURANCE_CALC
,  ON_BALANCE_NET_BANK_INSURANCE
,   round(convert(float,REPLACE(LTRIM(RTRIM(isnull(ON_BALANCE_NET_BANK_INSURANCE,'0'))),',','.')),6)  
AS ON_BALANCE_NET_BANK_INSURANCE_CALC	
,  ON_BALANCE_BANK_COMMISSIONS
,   round(convert(float,REPLACE(LTRIM(RTRIM(isnull(ON_BALANCE_BANK_COMMISSIONS,'0'))),',','.')),6)  
AS ON_BALANCE_BANK_COMMISSIONS_CALC	
,  ACTUAL_GROSS_BANK_INSURANCE
,   round(convert(float,REPLACE(LTRIM(RTRIM(isnull(ACTUAL_GROSS_BANK_INSURANCE,'0'))),',','.')),6)  
AS ACTUAL_GROSS_BANK_INSURANCE_CALC		
,  ACTUAL_NET_BANK_INSURANCE
,   round(convert(float,REPLACE(LTRIM(RTRIM(isnull(ACTUAL_NET_BANK_INSURANCE,'0'))),',','.')),6)  
AS ACTUAL_NET_BANK_INSURANCE_CALC		
,  ACTUAL_COMMISSIONS_BANK	
,   round(convert(float,REPLACE(LTRIM(RTRIM(isnull(ACTUAL_COMMISSIONS_BANK,'0'))),',','.')),6)  
AS ACTUAL_COMMISSIONS_BANK_CALC
,  CUSTOMER_CDI_CODE	
,  INSURANCE_ACCOUNT_ID	
,  INSURANCE_ACCOUNT_CODE	

FROM    OPENROWSET(BULK 'X:/DATA/Commissions/DATA/X_COM_AXA_COMMISSIONS.csv', FORMATFILE = 'X:/DATA/Commissions/FF/X_COM_AXA_COMMISSIONS_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz

