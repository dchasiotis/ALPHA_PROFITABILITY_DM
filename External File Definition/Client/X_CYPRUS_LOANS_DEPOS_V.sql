
--X_CYPRUS_LOANS_DEPOS_V
ALTER VIEW [STG].[X_CYPRUS_LOANS_DEPOS_V]
AS
SELECT
	RECORD_TYPE
,	ACCOUNT_NUMBER
, ISNULL (CASE WHEN SUBSTRING(ltrim(rtrim(ACCOUNT_NUMBER)),1,2)='2_' THEN REPLACE(LTRIM(REPLACE(ltrim(rtrim(ACCOUNT_NUMBER)), '2_', ' ')), ' ', '0') ELSE LEFT (ltrim(rtrim(ACCOUNT_NUMBER)), LEN (ltrim(rtrim(ACCOUNT_NUMBER)))-1) END , '0')  AS ACCOUNT_NUMBER_CALC   ---- ACCOUNT_CODE ----
,	ACCOUNT_STATUS
, CASE WHEN ltrim(rtrim(isnull(ACCOUNT_STATUS,''))) = '' THEN '0' ELSE ltrim(rtrim(ACCOUNT_STATUS)) END  AS ACCOUNT_STATUS_CALC  --- ACCOUNT_STATUS_CODE ---
,	ACCRUAL_BASIS
, CASE WHEN ltrim(rtrim(isnull(ACCRUAL_BASIS,''))) = '' THEN '0' ELSE ltrim(rtrim(ACCRUAL_BASIS)) END  AS ACCRUAL_BASIS_CALC   ---- ACCOUNT_ACCRUAL_BASIS_CODE ---- 
,	ACCRUED_INTEREST_MONTH_SIGN
,	ACCRUED_INTEREST_MONTH_CCY
,	ACCRUED_INTEREST_MONTH_EUR
, round(convert(float,REPLACE(ltrim(rtrim(isnull(ACCRUED_INTEREST_MONTH_EUR,'0'))),',', '.'))/100,2)  as ACCRUED_INTEREST_MONTH_EUR_CALC  ----MTD_NII_INTEREST_EUR ---- 
,	ACCRUED_INTEREST_YTD_CCY
,	ACCRUED_INTEREST_YTD_EUR
,	AS_OF_DATE
,	AVERAGE_BALANCE_MONTH_CCY
, round(convert(float,REPLACE(ltrim(rtrim(isnull(AVERAGE_BALANCE_MONTH_CCY,'0'))),',', '.'))/100,2) as AVERAGE_BALANCE_MONTH_CCY_CALC  ---- AVG_BALANCE_FX ----
,	AVERAGE_BALANCE_MONTH_EUR
, round(convert(float,REPLACE(ltrim(rtrim(isnull(AVERAGE_BALANCE_MONTH_EUR,'0'))),',', '.'))/100,2) as AVERAGE_BALANCE_MONTH_EUR_CALC  --- AVG_BALANCE_EUR ---
,	AVERAGE_BALANCE_YTD_CCY
,	AVERAGE_BALANCE_YTD_EUR
,	LEGAL_ENTITY
,	BRANCH_MAINT
, CASE WHEN ltrim(rtrim(isnull(BRANCH_MAINT,''))) = ''  THEN '0' ELSE ltrim(rtrim(BRANCH_MAINT)) END  AS BRANCH_MAINT_CALC   ---- ACCOUNT_BRANCH_CODE ----
,	BRANCH_OPEN
,	COST_CENTER_CODE
,	ORIGINATING_COUNTRY
, CASE WHEN ltrim(rtrim(isnull(ORIGINATING_COUNTRY,''))) = '' THEN  '0' ELSE ltrim(rtrim(ORIGINATING_COUNTRY)) END   AS ORIGINATING_COUNTRY_CALC  --- ORIG_COUNTRY ---
,	ORIGINATING_UNIT
, CASE WHEN ltrim(rtrim(ISNULL(ORIGINATING_UNIT,''))) = '' THEN  '0' ELSE ltrim(rtrim(ORIGINATING_UNIT)) END   AS ORIGINATING_UNIT_CALC   ---- ORIG_UNIT ----
,	ORIGINATING_BRANCH
,	CURRENCY_CODE
, case when ltrim(rtrim(isnull(CURRENCY_CODE,''))) = '' then '-'   ---- ACCOUNT_CURRENCY_ISO ----
       else ltrim(rtrim(CURRENCY_CODE)) end  AS CURRENCY_CODE_CALC
,	CURRENT_BOOK_BAL_CCY
, round(convert(float,REPLACE(ltrim(rtrim(isnull(CURRENT_BOOK_BAL_CCY,'0'))),',', '.'))/100,2) * CASE WHEN ltrim(rtrim(ACCOUNT_STATUS))='1' THEN 0 ELSE 1 END as CURRENT_BOOK_BAL_CCY_CALC   --- EOP_BALANCE_FX ----
,	CURRENT_BOOK_BAL_EUR
, round(convert(float,REPLACE(ltrim(rtrim(isnull(CURRENT_BOOK_BAL_EUR,'0'))),',', '.'))/100,2) * CASE WHEN ltrim(rtrim(ACCOUNT_STATUS))='1' THEN 0 ELSE 1 END as CURRENT_BOOK_BAL_EUR_CALC   ---- EOP_BALANCE_EUR ----
,	CUSTOMER_CATEGORY
,	CUSTOMER_FLAG
, CASE WHEN ltrim(rtrim(ISNULL(CUSTOMER_FLAG,''))) = '' THEN '0' ELSE ltrim(rtrim(CUSTOMER_FLAG)) END   AS CUSTOMER_FLAG_CALC   --- CLIENT_MONITORING_UNIT_CODE ---
,	CUSTOMER_FLAG_ALPHA_BANK
, CASE WHEN ltrim(rtrim(isnull(CUSTOMER_FLAG_ALPHA_BANK,''))) = '' THEN '0' ELSE ltrim(rtrim(CUSTOMER_FLAG_ALPHA_BANK)) END AS CUSTOMER_FLAG_ALPHA_BANK_CALC   ---- CLIENT_CL_TYPE_CODE ----
, CUSTOMER_NUMBER
--, case when isnumeric(ltrim(rtrim(isnull(CUSTOMER_NUMBER,'')))) = 0 then '0'  ------- CLIENT_CODE
--  else convert(nvarchar,convert(bigint,ltrim(rtrim(isnull(CUSTOMER_NUMBER,''))))) end AS CUSTOMER_NUMBER_CALC
, ISNULL(COALESCE(NULLIF(REPLACE(LTRIM(REPLACE(ltrim(rtrim(CUSTOMER_NUMBER)), '0', ' ')), ' ', '0'),''), '0'), '0' )  AS CUSTOMER_NUMBER_CALC  ---- CLIENT_CODE ----
,	CUSTOMER_NAME
, case when ltrim(rtrim(isnull(CUSTOMER_NAME,''))) = '' then '-'   ---- CLIENT_NAME ----
       else ltrim(rtrim(CUSTOMER_NAME)) end  AS CUSTOMER_NAME_CALC
,	CUSTOMER_TAX_CODE
, case when ltrim(rtrim(isnull(CUSTOMER_TAX_CODE,''))) = '' then '-'   ----- CLIENT_AFM_CODE -----   
       else ltrim(rtrim(CUSTOMER_TAX_CODE)) end  AS CUSTOMER_TAX_CODE_CALC
,	GL_ACCOUNT_NUMBER
,	GL_ACCOUNT_TYPE
, CASE WHEN ltrim(rtrim(isnull(GL_ACCOUNT_TYPE,''))) = ''  THEN '0' ELSE ltrim(rtrim(GL_ACCOUNT_TYPE)) END  AS  GL_ACCOUNT_TYPE_CALC  ---- ACCOUNT_GL_ACCOUNT_TYPE_CODE---
,	INTEREST_RATE
, round(convert(float,REPLACE(ltrim(rtrim(isnull(INTEREST_RATE,'0'))),',', '.'))/100000,6) as INTEREST_RATE_CALC  --- ACCOUNT_RTE_NII_NOMINAL ---
,	CUSTOMER_SPREAD
,	BASE_RATE_INDEX
,	FEE_RATE
,	MATURITY_DATE
,cast(case when ltrim(rtrim(isnull(MATURITY_DATE,''))) = '' then '9999-01-01'  ------ACCOUNT_MATURITY_DATE
      when left(ltrim(rtrim(MATURITY_DATE)) ,2) < '19' then '9999-01-01'
      else ltrim(rtrim(MATURITY_DATE)) end as date) as MATURITY_DATE_CALC
,	NEXT_PAYMENT_DATE
,	NEXT_REPRICE_DATE
,cast(case when ltrim(rtrim(isnull(NEXT_REPRICE_DATE,''))) = '' then '9999-01-01'  ------ACCOUNT_NEXT_REPRICE_DATE  
      when left(ltrim(rtrim(NEXT_REPRICE_DATE)) ,2) < '19' then '9999-01-01'
      else ltrim(rtrim(NEXT_REPRICE_DATE)) end as date) as NEXT_REPRICE_DATE_CALC
,	ORIGINAL_BALANCE_CCY
, round(convert(float,REPLACE(ltrim(rtrim(isnull(ORIGINAL_BALANCE_CCY,'0'))),',', '.'))/100,2) as ORIGINAL_BALANCE_CCY_CALC   ---- ACCOUNT_ORIGINAL_BALANCE_FX ----
,	ORIGINAL_BALANCE_EUR
, round(convert(float,REPLACE(ltrim(rtrim(isnull(ORIGINAL_BALANCE_EUR,'0'))),',', '.'))/100,2) as ORIGINAL_BALANCE_EUR_CALC   ---- ACCOUNT_ORIGINAL_BALANCE_EUR ----
,	ORIGINAL_TERM
,	ORIGINATION_DATE
,cast(case when ltrim(rtrim(isnull(ORIGINATION_DATE,''))) = '' then '9999-01-01'  ------ACCOUNT_ORIGINATION_DATE
      when left(ltrim(rtrim(ORIGINATION_DATE)) ,2) < '19' then '9999-01-01'
      else ltrim(rtrim(ORIGINATION_DATE)) end as date) as ORIGINATION_DATE_CALC
,	PAYMENT_AMOUNT
,	PAYMENT_FREQUENCY
,	PAYMENT_FREQUENCY_INCREMENT
,	PAYMENT_TYPE
, CASE WHEN ltrim(rtrim(isnull(PAYMENT_TYPE,''))) = '' THEN '0' ELSE ltrim(rtrim(PAYMENT_TYPE)) END  AS PAYMENT_TYPE_CALC   ---- ACCOUNT_PAYMENT_TYPE_CODE ----
,	PERCENT_OWNED
,	PREVIOUS_REPRICE_DATE
,cast(case when ltrim(rtrim(isnull(PREVIOUS_REPRICE_DATE,''))) = '' then '9999-01-01'  ------ACCOUNT_PREVIOUS_REPRICE_DATE
      when left(ltrim(rtrim(PREVIOUS_REPRICE_DATE)) ,2) < '19' then '9999-01-01'
      else ltrim(rtrim(PREVIOUS_REPRICE_DATE)) end as date) as PREVIOUS_REPRICE_DATE_CALC
,	PRODUCT_CODE
, CASE WHEN ltrim(rtrim(isnull(PRODUCT_CODE,''))) = '' THEN '0' ELSE ltrim(rtrim(PRODUCT_CODE)) END  AS PRODUCT_CODE_CALC   ---- ACCOUNT_DWH_PRODUCT_CODE ----
,	PRODUCT_DESCRIPTION
,	RATE_CHANGE_FREQUENCY
,	RATE_CHANGE_FREQUENCY_INCREMENT
,	RATE_FLAG
, CASE WHEN ltrim(rtrim(isnull(RATE_FLAG,''))) = '' THEN '0' ELSE ltrim(rtrim(RATE_FLAG)) END  AS RATE_FLAG_CALC   ----  ACCOUNT_RATE_TYPE_CODE ----
,	REAL_CLOSE_DATE
,cast(case when ltrim(rtrim(isnull(REAL_CLOSE_DATE,''))) = '' then '9999-01-01'  ------ACCOUNT_REAL_CLOSE_DATE
      when left(ltrim(rtrim(REAL_CLOSE_DATE)) ,2) < '19' then '9999-01-01'
      else ltrim(rtrim(REAL_CLOSE_DATE)) end as date) as REAL_CLOSE_DATE_CALC
,	BASE_RATE_DESCRIPTION
,	CUSTOMER_TYPE
, CASE WHEN ltrim(rtrim(isnull(CUSTOMER_TYPE,''))) = '' THEN '0' ELSE ltrim(rtrim(CUSTOMER_TYPE)) END  AS CUSTOMER_TYPE_CALC  --- CLIENT_CL_CATEGORY_CODE ----
,	CUSTOMER_TYPE_DESCRIPTION
, EBA_STATUS
, STAGE
, ASSESSMENT_TYPE
, PRODUCT_TYPE
, SPV_FLAG
, SPV_TYPE
, CONVENTION_TYPE
, BASIC_INTEREST_RATE
, GROUP_FLAG
, LCR_STABLE_CODE
, LCR_BUSINESSUNIT_CODE
, LCR_TRANSACTION_TYPE_CODE
, LCR_OPERATIONAL_AMOUNT
, HFS_INDICATOR

FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_CYPRUS_LOANS_DEPOS.txt', 
FORMATFILE = 'X:/DATA/CLIENT/FF/X_CYPRUS_LOANS_DEPOS_FF.xml',
FIRSTROW=2
) as zzz

WHERE RECORD_TYPE='2'





