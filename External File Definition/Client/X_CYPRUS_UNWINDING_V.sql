ALTER VIEW STG.X_CYPRUS_UNWINDING_V
AS
SELECT 
  AS_OF_DATE
, ACCOUNT
, CASE WHEN isnull(ACCOUNT,'') = '' THEN '0'  ELSE ltrim(rtrim(ACCOUNT)) END  AS ACCOUNT_CALC 
, UNWINDING_OF_INTEREST_MTD 
, round(convert(float,REPLACE(replace(LTRIM(RTRIM(isnull(UNWINDING_OF_INTEREST_MTD,'0'))),'.',''),',','.')),2)  AS UNWINDING_OF_INTEREST_MTD_CALC 
, LEGAL_ENTITY


FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_CYPRUS_UNWINDING.csv',
FORMATFILE = 'X:/DATA/CLIENT/FF/X_CYPRUS_UNWINDING_FF.txt', FIRSTROW = 3) as zzz