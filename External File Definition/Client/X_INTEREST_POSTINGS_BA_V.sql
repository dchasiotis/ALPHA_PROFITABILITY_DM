ALTER VIEW STG.X_INTEREST_POSTINGS_BA_V
AS
SELECT
	ASSET_CLASS_FINREP
,	[CONTRACT]
,   CASE WHEN [CONTRACT] IS NULL THEN '0'
         WHEN LEN([CONTRACT]) <= 2 THEN '0'
         WHEN RIGHT(LTRIM(RTRIM([CONTRACT])),2) IN ('07','09','11') THEN ISNULL(COALESCE(NULLIF(REPLACE(LTRIM(REPLACE(LEFT(ltrim(rtrim([CONTRACT])),15), '0', ' ')), ' ', '0'),''), '0'), '0' )
		 ELSE LEFT(LTRIM([CONTRACT]),15) END AS [CONTRACT_CALC]
,	SOURCE_SYSTEM_C11SRCSY
,	ISNULL(SOURCE_SYSTEM_C11SRCSY,'0') AS SOURCE_SYSTEM_BA
,	SEGMENT_ZSEGMENT
,	GL_CODE_2_FPCHARS_ZGLCODE2
,	CLASSIFICATION_C55HOLDCT
,	STAGE_INDICATOR_ZSTAGE
,	POCI_FLAG_ZPOCI_FLG
,	ASSET_CLASS_ZASSETCLS
,	INTEREST_ACCRUALS_REVERSAL
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(INTEREST_ACCRUALS_REVERSAL,'0'))),'.',''),',','.')),2)  AS INTEREST_ACCRUALS_REVERSAL_CALC
,	NAI_ACCRUALS_REVERSAL
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(NAI_ACCRUALS_REVERSAL,'0'))),'.',''),',','.')),2)  AS NAI_ACCRUALS_REVERSAL_CALC
,	INTEREST_POSTINGS_SOURCE
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(INTEREST_POSTINGS_SOURCE,'0'))),'.',''),',','.')),2)  AS INTEREST_POSTINGS_SOURCE_CALC
,	ACCRUAS_SEC
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(ACCRUAS_SEC,'0'))),'.',''),',','.')),2)  AS ACCRUAS_SEC_CALC
,	NAI_POSTINGS
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(NAI_POSTINGS,'0'))),'.',''),',','.')),2)  AS NAI_POSTINGS_CALC
,	NAI_CREDIT
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(NAI_CREDIT,'0'))),'.',''),',','.')),2)  AS NAI_CREDIT_CALC
,	INTEREST_ACCRUALS
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(INTEREST_ACCRUALS,'0'))),'.',''),',','.')),2)  AS INTEREST_ACCRUALS_CALC
,	NAI_ACCRUALS
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(NAI_ACCRUALS,'0'))),'.',''),',','.')),2)  AS NAI_ACCRUALS_CALC
,	N3869_ACCRUALS
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(N3869_ACCRUALS,'0'))),'.',''),',','.')),2)  AS N3869_ACCRUALS_CALC
,	N3869
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(N3869,'0'))),'.',''),',','.')),2)  AS N3869_CALC
,	SUM_OF_GROSS_INTEREST
,	DEFERRALS
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(DEFERRALS,'0'))),'.',''),',','.')),2)  AS DEFERRALS_CALC
,	FVA_UNWINDING_POS
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(FVA_UNWINDING_POS,'0'))),'.',''),',','.')),2)  AS FVA_UNWINDING_POS_CALC
,	IMPAIRMENT_CORRECTION_POS
,   round(convert(float,REPLACE(REPLACE(LTRIM(RTRIM(isnull(IMPAIRMENT_CORRECTION_POS,'0'))),'.',''),',','.')),2)  AS IMPAIRMENT_CORRECTION_POS_CALC
,	SUM_OF_NET_INTEREST
FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_INTEREST_POSTINGS_BA.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_INTEREST_POSTINGS_BA_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz
