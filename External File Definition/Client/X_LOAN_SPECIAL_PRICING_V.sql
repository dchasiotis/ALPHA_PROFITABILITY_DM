ALTER VIEW STG.X_LOAN_SPECIAL_PRICING_V
AS
SELECT
  GROUP_CODE
, CDI
, case when replace(ltrim(replace(replace(isnull(CDI, '0'), ' ', '0'), '0', ' ')), ' ', '0')='' then '0' else  replace(ltrim(replace(replace(isnull(CDI, '0'), ' ', '0'), '0', ' ')), ' ', '0') end CDI_CALC
, CUSTOMER_NAME
, ACCOUNT_CODE
, STATUS_CODE
, OPEN_DATE
, CONVERT(DATE,LTRIM(RTRIM(REPLACE(isnull(OPEN_DATE,''),'/','-'))),103 ) AS OPEN_DATE_CALC	
, DISBURSEMENT_DATE
, CONVERT(DATE,LTRIM(RTRIM(REPLACE(isnull(DISBURSEMENT_DATE,''),'/','-'))),103 ) AS DISBURSEMENT_DATE_CALC	
, DISBURSEMENT_AMOUNT
, round(convert(float,REPLACE(REPLACE(ltrim(rtrim(DISBURSEMENT_AMOUNT)), '.', ''),',', '.')),2) as DISBURSEMENT_AMOUNT_CALC
, BFCS_DESC
, LIQUIDITY_PREMIUM
, ICAP

FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_LOAN_SPECIAL_PRICING.CSV', FORMATFILE = 'X:/DATA/CLIENT/FF/X_LOAN_SPECIAL_PRICING_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz
