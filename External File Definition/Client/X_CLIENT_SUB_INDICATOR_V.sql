alter VIEW STG.X_CLIENT_SUB_INDICATOR_V
AS
SELECT
	ENTITY_CODE
,   ltrim(rtrim(ISNULL(ENTITY_CODE,'0')))  AS ENTITY_CODE_CALC
,	CLIENT_CODE
,   ltrim(rtrim(ISNULL(CLIENT_CODE, '0' )))  AS CLIENT_CODE_CALC
,	CLIENT_NAME
,   ltrim(rtrim(ISNULL(CLIENT_NAME, '-' )))  AS CLIENT_NAME_CALC
,	CLIENT_SUB_CODE
,   ltrim(rtrim(ISNULL(CLIENT_SUB_CODE, '0' )))  AS CLIENT_SUB_CODE_CALC
,	CLIENT_SUB_NAME
,   ltrim(rtrim(ISNULL(CLIENT_SUB_NAME, '-' )))  AS CLIENT_SUB_NAME_CALC
FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_CLIENT_SUB_INDICATOR.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_CLIENT_SUB_INDICATOR_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz


