ALTER VIEW STG.X_MERGED_ACCOUNTS_V
AS
SELECT
REF_MONTH
, PARENT_SOURCE_SYSTEM_CODE
,   CASE WHEN isnull(PARENT_SOURCE_SYSTEM_CODE,'') = ''  THEN '0' 
         ELSE LTRIM(RTRIM(PARENT_SOURCE_SYSTEM_CODE)) END  AS PARENT_SOURCE_SYSTEM_CODE_CALC
, PARENT_ACCOUNT_CODE
,   CASE WHEN isnull(PARENT_ACCOUNT_CODE,'') = ''  THEN '0' 
         ELSE LTRIM(RTRIM(PARENT_ACCOUNT_CODE)) END  AS PARENT_ACCOUNT_CODE_CALC
, CHILD_SOURCE_SYSTEM_CODE
,   CASE WHEN isnull(CHILD_SOURCE_SYSTEM_CODE,'') = ''  THEN '0' 
         ELSE LTRIM(RTRIM(CHILD_SOURCE_SYSTEM_CODE)) END  AS CHILD_SOURCE_SYSTEM_CODE_CALC
, CHILD_ACCOUNT_CODE
,   CASE WHEN isnull(CHILD_ACCOUNT_CODE,'') = ''  THEN '0' 
         ELSE LTRIM(RTRIM(CHILD_ACCOUNT_CODE)) END  AS CHILD_ACCOUNT_CODE_CALC
, PARENT_DATE
,cast (case when ltrim(rtrim(isnull(PARENT_DATE,''))) = '' then '9999-01-01'  ------- ACCOUNT_MATURITY_DATE
      when left(ltrim(rtrim(PARENT_DATE)) ,2) < '19' then '9999-01-01'
      else ltrim(rtrim(PARENT_DATE)) end as date) as PARENT_DATE_CALC
, PARENT_REFERENCE_REASON
,   CASE WHEN isnull(PARENT_REFERENCE_REASON,'') = ''  THEN '-' 
         ELSE LTRIM(RTRIM(PARENT_REFERENCE_REASON)) END  AS PARENT_REFERENCE_REASON_CALC

FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_MERGED_ACCOUNTS.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_MERGED_ACCOUNTS_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz
