CREATE VIEW STG.X_MERGED_LEGAL_ENTITES_V
AS
SELECT
  LEGAL_ENTITIES_CONSOLIDATION_ACTIVE_CUSTOMER_CDI_CODE
,   CASE WHEN isnull(LEGAL_ENTITIES_CONSOLIDATION_ACTIVE_CUSTOMER_CDI_CODE,'') = ''  THEN '0' 
         ELSE LTRIM(RTRIM(LEGAL_ENTITIES_CONSOLIDATION_ACTIVE_CUSTOMER_CDI_CODE)) END  AS LEGAL_ENTITIES_CONSOLIDATION_ACTIVE_CUSTOMER_CDI_CODE_CALC
, LEGAL_ENTITIES_CONSOLIDATION_INACTIVE_CUSTOMER_CDI_CODE	
,   CASE WHEN isnull(LEGAL_ENTITIES_CONSOLIDATION_INACTIVE_CUSTOMER_CDI_CODE,'') = ''  THEN '0' 
         ELSE LTRIM(RTRIM(LEGAL_ENTITIES_CONSOLIDATION_INACTIVE_CUSTOMER_CDI_CODE)) END  AS LEGAL_ENTITIES_CONSOLIDATION_INACTIVE_CUSTOMER_CDI_CODE_CALC
, LEGAL_ENTITIES_CONSOLIDATION_SOURCE_SYSTEM_CODE	
,   CASE WHEN isnull(LEGAL_ENTITIES_CONSOLIDATION_SOURCE_SYSTEM_CODE,'') = ''  THEN '0' 
         ELSE LTRIM(RTRIM(LEGAL_ENTITIES_CONSOLIDATION_SOURCE_SYSTEM_CODE)) END  AS LEGAL_ENTITIES_CONSOLIDATION_SOURCE_SYSTEM_CODE_CALC
, LEGAL_ENTITIES_CONSOLIDATION_TYPE_CODE	
, LEGAL_ENTITIES_CONSOLIDATION_TYPE_DESCRIPTION	
, LEGAL_ENTITIES_CONSOLIDATION_DATE	
,cast (case when ltrim(rtrim(isnull(LEGAL_ENTITIES_CONSOLIDATION_DATE,''))) = '' then '9999-01-01'
      when left(ltrim(rtrim(LEGAL_ENTITIES_CONSOLIDATION_DATE)) ,2) < '19' then '9999-01-01'
      else ltrim(rtrim(LEGAL_ENTITIES_CONSOLIDATION_DATE)) end as date) as LEGAL_ENTITIES_CONSOLIDATION_DATE_CALC
, LEGAL_ENTITIES_CONSOLIDATION_REFERENCE_DATE	
,cast (case when ltrim(rtrim(isnull(LEGAL_ENTITIES_CONSOLIDATION_REFERENCE_DATE,''))) = '' then '9999-01-01' 
      when left(ltrim(rtrim(LEGAL_ENTITIES_CONSOLIDATION_REFERENCE_DATE)) ,2) < '19' then '9999-01-01'
      else ltrim(rtrim(LEGAL_ENTITIES_CONSOLIDATION_REFERENCE_DATE)) end as date) as LEGAL_ENTITIES_CONSOLIDATION_REFERENCE_DATE_CALC

FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_MERGED_LEGAL_ENTITIES.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_MERGED_LEGAL_ENTITIES_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz
