
CREATE VIEW [STG].[X_FINANCE_V]
AS
SELECT
	ACCOUNT_CODE	
,   CASE WHEN isnull(ACCOUNT_CODE,'') = ''  THEN '0' 
    ELSE ACCOUNT_CODE END  AS ACCOUNT_CODE_CALC		
,	ACCOUNT_CUSTOMER_CDI_CODE	
,   CASE WHEN isnull(ACCOUNT_CUSTOMER_CDI_CODE,'') = ''  THEN '0' 
    ELSE ACCOUNT_CUSTOMER_CDI_CODE END  AS ACCOUNT_CUSTOMER_CDI_CODE_CALC		
,   ACCOUNT_FIRST_BENEFICIARY_CDI_CODE	
,   CASE WHEN isnull(ACCOUNT_FIRST_BENEFICIARY_CDI_CODE,'') = ''  THEN '0' 
    ELSE ACCOUNT_FIRST_BENEFICIARY_CDI_CODE END  AS ACCOUNT_FIRST_BENEFICIARY_CDI_CODE_CALC		
,   CUSTOMER_ACCOUNT	
,   CASE WHEN isnull(CUSTOMER_ACCOUNT,'') = ''  THEN '0' 
    ELSE CUSTOMER_ACCOUNT END  AS CUSTOMER_ACCOUNT_CALC			
,   CUSTOMER_PORTFOLIO			
,   SERVICE_CHANNEL_CODE			
,   SERVICE_CHANNEL_DESCRIPTION			
,   BRANCH_CODE	
,   CASE WHEN isnull(BRANCH_CODE,'') = ''  THEN '0' 
    ELSE BRANCH_CODE END  AS BRANCH_CODE_CALC				
,   STOCK_EXCHANGE_CODE			
,   STOCK_EXCHANGE_COUNTRY_CODE			
,   PRODUCT_CODE			
,   ISIN			
,   ISIN_NAME			
,   CURRENCY_CODE			
,   QUANTITY			
,   AMOUNT	
,   round(convert(float,REPLACE(LTRIM(RTRIM(isnull(AMOUNT,0))),',','.')),2)  AS AMOUNT_CALC
,   AMOUNT_IN_EURO	
,   round(convert(float,REPLACE(LTRIM(RTRIM(isnull(AMOUNT_IN_EURO,0))),',','.')),2)  AS AMOUNT_IN_EURO_CALC		
,   INVESTMENT_AMOUNT	
,   round(convert(float,REPLACE(LTRIM(RTRIM(isnull(INVESTMENT_AMOUNT,0))),',','.')),2)  AS INVESTMENT_AMOUNT_CALC		
,   SOURCE_SYSTEM_CODE		
,   REFERENCE_DATE			
FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_FINANCE.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_FINANCE_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz

