ALTER VIEW STG.X_CYPRUS_LOANS_DEPOS_DAILY_V
AS
SELECT
           RECORD_TYPE
		,  ACCOUNT_NUMBER
	    , ISNULL (CASE WHEN SUBSTRING(ltrim(rtrim(ACCOUNT_NUMBER)),1,2)='2_' THEN REPLACE(LTRIM(REPLACE(ltrim(rtrim(ACCOUNT_NUMBER)), '2_', ' ')), ' ', '0') ELSE LEFT (ltrim(rtrim(ACCOUNT_NUMBER)), LEN (ltrim(rtrim(ACCOUNT_NUMBER)))-1) END , '0')  AS ACCOUNT_NUMBER_CALC   ---- ACCOUNT_CODE ----
		,  ACCOUNT_STATUS
		,  ACCRUALS_BASIS
		,  ACCRUED_INTRST_MONTH_SIGN
		,  ACCRUED_INTRST_MONTH
		,  ACCRUED_INTRST_MONTH_EURO
		,  ACCRUED_INTRST_YTD
		,  ACCRUED_INTRST_YTD_EURO
		,  AS_OF_DATE
		,  AVERAGE_BALANCE_MONTH
		,  AVERAGE_BALANCE_MONTH_EURO
		,  AVERAGE_BALANCE_YTD
		,  AVERAGE_BALANCE_YTD_EURO
		,  LEGAL_ENTITY
		,  BRANCH_MAINT
		,  BRANCH_OPEN
		,  COST_CENTER
		,  ORIGINATING_COUNTRY
		, CASE WHEN ltrim(rtrim(isnull(ORIGINATING_COUNTRY,''))) = '' THEN  '0' ELSE ltrim(rtrim(ORIGINATING_COUNTRY)) END   AS ORIGINATING_COUNTRY_CALC  --- ORIG_COUNTRY ---
		,  ORIGINATING_UNIT
		,  ORIGINATING_BRANCH
		,  CURRENCY_CODE
		, case when ltrim(rtrim(isnull(CURRENCY_CODE,''))) = '' then '-'   ---- ACCOUNT_CURRENCY_ISO ----
          else ltrim(rtrim(CURRENCY_CODE)) end  AS CURRENCY_CODE_CALC
		,  CURRENT_BOOK_BAL_CCY
        ,  ROUND(cast(REPLACE(REPLACE(ISNULL(CURRENT_BOOK_BAL_CCY,'0'), '.', ''),',', '.') as float) ,6) as CURRENT_BOOK_BAL_CCY_CALC
		,  CURRENT_BOOK_BAL_EUR
        ,  ROUND(cast(REPLACE(REPLACE(ISNULL(CURRENT_BOOK_BAL_EUR,'0'), '.', ''),',', '.') as float) ,6) as CURRENT_BOOK_BAL_EUR_CALC
		,  CUSTOMER_CATEGORY
		,  CUSTOMER_FLAG
		,  CASE WHEN ltrim(rtrim(ISNULL(CUSTOMER_FLAG,''))) = '' THEN '0' ELSE RIGHT('00'+ltrim(rtrim(CUSTOMER_FLAG)), 2)  END  AS CUSTOMER_FLAG_CALC   --- CLIENT_MONITORING_UNIT_CODE ---
		,  CUSTOMER_FLAG_ALPHA_BANK
		,  CASE WHEN ltrim(rtrim(isnull(CUSTOMER_FLAG_ALPHA_BANK,''))) = '' THEN '0' ELSE RIGHT('00'+ltrim(rtrim(CUSTOMER_FLAG_ALPHA_BANK)), 2)  END  AS CUSTOMER_FLAG_ALPHA_BANK_CALC  ---- CLIENT_CL_TYPE_CODE ----
		,  CUSTOMER_NUMBER
		, ISNULL(COALESCE(NULLIF(REPLACE(LTRIM(REPLACE(ltrim(rtrim(CUSTOMER_NUMBER)), '0', ' ')), ' ', '0'),''), '0'), '0' )  AS CUSTOMER_NUMBER_CALC  ---- CLIENT_CODE ----
		,  CUSTOMER_NAME
		, case when ltrim(rtrim(isnull(CUSTOMER_NAME,''))) = '' then '-'   ---- CLIENT_NAME ----
          else ltrim(rtrim(CUSTOMER_NAME)) end  AS CUSTOMER_NAME_CALC
		,  CUSTOMER_TAX_CODE
		, case when ltrim(rtrim(isnull(CUSTOMER_TAX_CODE,''))) = '' then '-'   ----- CLIENT_AFM_CODE -----   
          else ltrim(rtrim(CUSTOMER_TAX_CODE)) end  AS CUSTOMER_TAX_CODE_CALC
		,  GL_ACCOUNT_NUMBER
		,  GL_ACCOUNT_TYPE
		, CASE WHEN ltrim(rtrim(isnull(GL_ACCOUNT_TYPE,''))) = ''  THEN '0' ELSE ltrim(rtrim(GL_ACCOUNT_TYPE)) END  AS  GL_ACCOUNT_TYPE_CALC  ---- ACCOUNT_GL_ACCOUNT_TYPE_CODE---
		,  INTEREST_RATE
        ,  ROUND(cast(REPLACE(REPLACE(ISNULL(INTEREST_RATE,'0'), '.', ''),',', '.') as float) ,6) as INTEREST_RATE_CALC
		,  CUSTOMER_SPREAD
		,  BASE_RATE_INDEX
		,  MATURITY_DATE
		,  NEXT_PAYMENT_DATE
		,  NEXT_REPRICE_DATE
		,  ORIGINAL_BALANCE
		,  ORIGINAL_BALANCE_EURO
		,  ORIGINAL_TERM
		,  ORIGINATION_DATE
		,  cast(case when ltrim(rtrim(isnull(ORIGINATION_DATE,''))) = '' then '9999-01-01'  ------ACCOUNT_ORIGINATION_DATE
           when left(ltrim(rtrim(ORIGINATION_DATE)) ,2) < '19' then '9999-01-01'
           else ltrim(rtrim(ORIGINATION_DATE)) end as date) as ORIGINATION_DATE_CALC
		,  PAYMENT_AMOUNT
		,  PAYMENT_FREQUENCY
		,  PAYMENT_FREQUENCY_INCREMENT
		,  PAYMENT_TYPE
		,  PERCENT_OWNED
		,  PREVIOUS_REPRICE_DATE
		,  PRODUCT_CODE
		,  CASE WHEN ltrim(rtrim(isnull(PRODUCT_CODE,''))) = '' THEN '0' ELSE ltrim(rtrim(PRODUCT_CODE)) END  AS PRODUCT_CODE_CALC   ---- ACCOUNT_DWH_PRODUCT_CODE ----
		,  PRODUCT_DESCRIPTION
		,  RATE_CHANGE_FREQUENCY
		,  RATE_CHANGE_FREQUENCY_INCREMENT
		,  RATE_FLAG
		,  REAL_CLOSE_DATE
		,  PPDESCR
		,  CUSTOMER_TYPE
		,  ISNULL(SUBSTRING(CUSTOMER_TYPE,1,3),'0') AS CUSTOMER_TYPE_CALC
		--,  SUBSTRING(CUSTOMER_TYPE,0,CHARINDEX('-',CUSTOMER_TYPE,0)) AS CUSTOMER_TYPE_CALC
		--, CASE WHEN ltrim(rtrim(isnull(CUSTOMER_TYPE,''))) = '' THEN '0' ELSE ltrim(rtrim(CUSTOMER_TYPE)) END  AS CUSTOMER_TYPE_CALC  --- CLIENT_CL_CATEGORY_CODE ----


FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_CYPRUS_LOANS_DEPOS_DAILY.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_CYPRUS_LOANS_DEPOS_DAILY_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz


