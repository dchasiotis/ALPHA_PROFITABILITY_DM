ALTER VIEW STG.X_SAP_LOAN_FAIL_SPPI_CHARGE_V
AS
SELECT
	COMP_CODE
,	ANTISTOIXISH
,	REC_NUMBER
,	EPP
,	REC_TYPE
,	KK
,	SYS_ACCOUNT
, CASE WHEN RIGHT(SYS_ACCOUNT,2) IN ('07','09','11') 
  THEN COALESCE(NULLIF(REPLACE(LTRIM(REPLACE(LEFT([SYS_ACCOUNT],15), '0', ' ')), ' ', '0'),''), '0') 
  ELSE LEFT([SYS_ACCOUNT],15) END   AS SYS_ACCOUNT_CALC
, RIGHT(SYS_ACCOUNT,2) AS SOURCE_CODE_CALC
,	GL_ACCOUNT
,	REC_DATE
, CONVERT(DATE,LTRIM(RTRIM(REPLACE(isnull(REC_DATE,''),'/','-'))),103 ) AS REC_DATE_CALC			
,	VALUER_DATE
, CONVERT(DATE,LTRIM(RTRIM(REPLACE(isnull(VALUER_DATE,''),'/','-'))),103 ) AS VALUER_DATE_CALC			
,	CUR
,	AMOUNT
,   ISNULL(cast(REPLACE(REPLACE(AMOUNT, '.', ''),',', '.') as float) ,0) AS AMOUNT_CALC
FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_SAP_LOAN_FAIL_SPPI_CHARGE.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_SAP_LOAN_FAIL_SPPI_CHARGE_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz
