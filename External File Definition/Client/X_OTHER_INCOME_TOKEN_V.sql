
ALTER VIEW STG.X_OTHER_INCOME_TOKEN_V
AS
SELECT
	 FILE_NAME_
	,ACCOUNT
	,CDI
	,NETWORK
	,case when ltrim(rtrim(isnull(NETWORK,''))) = '' then '0'
     else right('0000' + NETWORK,4) end as NETWORK_CALC
	,EPM_UNIT
	,COMM_AMOUNT
	,round(convert(float,REPLACE(LTRIM(RTRIM(isnull([COMM_AMOUNT],0))),',','.')),2)  AS COMM_AMOUNT_CALC
	,CHARGE_TYPE
	,FILE_CATEGORY
	,CHANNEL


FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_OTHER_INCOME_TOKEN.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_OTHER_INCOME_TOKEN_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz

