
ALTER VIEW STG.X_K_LnD_CF_V
AS
SELECT
  FOLDER_SHORT_NAME
,   DEAL_TYPE
,   CCY_S_N
,   DEAL_ID
,   rtrim(ltrim(ISNULL(DEAL_ID, '0' )))  AS DEAL_ID_CALC
,	START_DATE
,   CONVERT(DATE,CASE WHEN LTRIM(RTRIM(REPLACE(isnull(START_DATE,''),'/','-'))) = '' THEN '9999-01-01'   
         ELSE LTRIM(RTRIM(REPLACE(START_DATE,'/','-'))) END,103 ) AS START_DATE_CALC
,   END_DATE
,   CONVERT(DATE,CASE WHEN LTRIM(RTRIM(REPLACE(isnull(END_DATE,''),'/','-'))) = '' THEN '9999-01-01'   
         ELSE LTRIM(RTRIM(REPLACE(END_DATE,'/','-'))) END,103 ) AS END_DATE_CALC
,   PRINCIPAL_AMOUNT
,   ROUND(cast(REPLACE(REPLACE(ISNULL(PRINCIPAL_AMOUNT,'0'), '.', ''),',', '.') as float) ,2) as PRINCIPAL_AMOUNT_CALC
,   RATE
,   ROUND(cast(REPLACE(REPLACE(ISNULL(RATE,'0'), '.', ''),',', '.') as float) ,6) as RATE_CALC
,   ADDITIVE_MARGIN
,   ROUND(cast(REPLACE(REPLACE(ISNULL(ADDITIVE_MARGIN,'0'), '.', ''),',', '.') as float) ,6) as ADDITIVE_MARGIN_CALC
FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_K_LnD_CF.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_K_LnD_CF_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz

