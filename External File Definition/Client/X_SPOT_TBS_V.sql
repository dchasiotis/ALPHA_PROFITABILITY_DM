CREATE VIEW [STG].[X_SPOT_TBS_V]
AS
SELECT
COUNTERPARTY_SHORT_NAME
, case when isnumeric(ltrim(rtrim(COUNTERPARTY_SHORT_NAME))) = 0 then '0'  ------ ACCOUNT_BRANCH_CODE
       when COUNTERPARTY_SHORT_NAME is null then '0'
	   when COUNTERPARTY_SHORT_NAME = '' then '0'
	   else RIGHT('0000'+ltrim(rtrim(COUNTERPARTY_SHORT_NAME)), 4) END  AS COUNTERPARTY_SHORT_NAME_CALC
,	TRADE_DATE
,	DEAL_STATUS
,	TYPE_OF_EVENT
,	AMOUNT_CUR1
,   ROUND(cast(REPLACE(REPLACE(ISNULL(AMOUNT_CUR1,'0'), '.', ''),',', '.') as float) ,2) as AMOUNT_CUR1_CALC
,	CURRENCY1_SHORT_NAME
,	AMOUNT_CUR2
,   ROUND(cast(REPLACE(REPLACE(ISNULL(AMOUNT_CUR2,'0'), '.', ''),',', '.') as float) ,2) as AMOUNT_CUR2_CALC
,	CURRENCY2_SHORT_NAME
,	SPOT_RATE
,   ROUND(cast(REPLACE(REPLACE(ISNULL(SPOT_RATE,'0'), '.', ''),',', '.') as float) ,6) as SPOT_RATE_CALC
,	AFM
,	ADDITIONALCOMMENTS
,	CLIENTCATEGORY
,	CLIENTNAME
,	CLIENTNUMBER
,   rtrim(ltrim(ISNULL(CLIENTNUMBER, '0' )))  AS CLIENTNUMBER_CALC
,	DEALID
,	DEALTYPE
,	VALUEDATE
,	DEAL_NUMBER
,   rtrim(ltrim(ISNULL(DEAL_NUMBER, '0' )))  AS DEAL_NUMBER_CALC
,	CLIENT_SPOT
,   ROUND(cast(REPLACE(REPLACE(ISNULL(CLIENT_SPOT,'0'), '.', ''),',', '.') as float) ,6) as CLIENT_SPOT_CALC
,	SPOT_MARGIN
,   USER_GROUP_NAME

FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_SPOT_TBS.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_SPOT_TBS_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz




GO


