

CREATE VIEW STG.X_K_COUNTERPARTY_V
AS
SELECT
	ENTITY_CODE
,   CASE WHEN isnull(ENTITY_CODE,'') = ''  THEN '0' ELSE replace(rtrim(ltrim(ENTITY_CODE)),'@','') END  AS ENTITY_CODE_CALC
,	CLIENT_CODE
,   CASE WHEN isnull(CLIENT_CODE,'') = '' THEN '0' ELSE CLIENT_CODE END  AS CLIENT_CODE_CALC
,	CLIENT_NAME
,   CASE WHEN isnull(CLIENT_NAME,'') = '' THEN '-' ELSE CLIENT_NAME END  AS CLIENT_NAME_CALC
,	CLIENT_COMPANY_NAME
,   CASE WHEN isnull(CLIENT_COMPANY_NAME,'') = '' THEN '-' ELSE CLIENT_COMPANY_NAME END  AS CLIENT_COMPANY_NAME_CALC
,	CLIENT_AFM_CODE
,   CASE WHEN isnull(CLIENT_AFM_CODE,'') = '' THEN '-' ELSE CLIENT_AFM_CODE END  AS CLIENT_AFM_CODE_CALC
,	CLIENT_MONITORING_UNIT_CODE
,   CASE WHEN isnull(CLIENT_MONITORING_UNIT_CODE,'') = '' THEN '0' ELSE CLIENT_MONITORING_UNIT_CODE END  AS CLIENT_MONITORING_UNIT_CODE_CALC
,	CLIENT_ANNOUNCEMENT_UNIT_CODE
,   CASE WHEN isnull(CLIENT_ANNOUNCEMENT_UNIT_CODE,'') = '' THEN '0' ELSE CLIENT_ANNOUNCEMENT_UNIT_CODE END  AS CLIENT_ANNOUNCEMENT_UNIT_CODE_CALC
,	CLIENT_MIS_UNIT_CODE
,   CASE WHEN isnull(CLIENT_MIS_UNIT_CODE,'') = '' THEN '0' ELSE CLIENT_MIS_UNIT_CODE END  AS CLIENT_MIS_UNIT_CODE_CALC
,	CLIENT_CRM_SEGMENT_CODE
,   CASE WHEN isnull(CLIENT_CRM_SEGMENT_CODE,'') = '' THEN '0' ELSE CLIENT_CRM_SEGMENT_CODE END  AS CLIENT_CRM_SEGMENT_CODE_CALC
,	CLIENT_CL_GROUP_CODE
,   CASE WHEN isnull(CLIENT_CL_GROUP_CODE,'') = '' THEN '0' ELSE CLIENT_CL_GROUP_CODE END  AS CLIENT_CL_GROUP_CODE_CALC
,	CLIENT_CL_RM_CODE
,   CASE WHEN isnull(CLIENT_CL_RM_CODE,'') = '' THEN '0' ELSE CLIENT_CL_RM_CODE END  AS CLIENT_CL_RM_CODE_CALC
,	CLIENT_CL_TYPE_CODE
,   CASE WHEN isnull(CLIENT_CL_TYPE_CODE,'') = '' THEN '0' ELSE CLIENT_CL_TYPE_CODE END  AS CLIENT_CL_TYPE_CODE_CALC
,	CLIENT_CL_CATEGORY_CODE
,   CASE WHEN isnull(CLIENT_CL_CATEGORY_CODE,'') = '' THEN '0' ELSE CLIENT_CL_CATEGORY_CODE END  AS CLIENT_CL_CATEGORY_CODE_CALC
,	CLIENT_CL_RATING_CODE
,   CASE WHEN isnull(CLIENT_CL_RATING_CODE,'') = '' THEN '0' ELSE CLIENT_CL_RATING_CODE END  AS CLIENT_CL_RATING_CODE_CALC
,	CLIENT_NETWORK_CODE
,   CASE WHEN isnull(CLIENT_NETWORK_CODE,'') = '' THEN '0' ELSE CLIENT_NETWORK_CODE END  AS CLIENT_NETWORK_CODE_CALC
,	CLIENT_BRANCH_CODE
,   CASE WHEN isnull(CLIENT_BRANCH_CODE,'') = '' THEN '0' ELSE right('0000'+ rtrim(ltrim(CLIENT_BRANCH_CODE)),4) END  AS CLIENT_BRANCH_CODE_CALC
,	CLIENT_STAKOD_CODE
,   CASE WHEN isnull(CLIENT_STAKOD_CODE,'') = '' THEN '0' ELSE CLIENT_STAKOD_CODE END  AS CLIENT_STAKOD_CODE_CALC
,	CLIENT_COUNTRY_CODE
,   CASE WHEN isnull(CLIENT_COUNTRY_CODE,'') = '' THEN '0' ELSE CLIENT_COUNTRY_CODE END  AS CLIENT_COUNTRY_CODE_CALC
,	CLIENT_SUB_CODE
,   CASE WHEN isnull(CLIENT_SUB_CODE,'') = '' THEN '0' ELSE CLIENT_SUB_CODE END  AS CLIENT_SUB_CODE_CALC
,	PARENT_CLIENT_CODE
FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_K_COUNTERPARTY.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_K_COUNTERPARTY_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz



