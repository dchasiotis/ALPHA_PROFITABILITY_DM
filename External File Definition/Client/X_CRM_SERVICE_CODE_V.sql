,   CRM_SEG_CODE 
,   ltrim(rtrim(ISNULL(CRM_SEG_CODE, '0' )))  AS CRM_SEG_CODE_CALC 
,   CRM_SEG 
,   REF_DATE

FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_CRM_SERVICE_CODE.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_CRM_SERVICE_CODE_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz
