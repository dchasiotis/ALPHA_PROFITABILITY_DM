CREATE VIEW STG.X_CRM_SERVICE_CODE_V
AS
SELECT
    CST_CDI_CODE 
,   ltrim(rtrim(ISNULL(CST_CDI_CODE, '0' )))  AS CST_CDI_CODE_CALC
,   CRM_CST_SVC_CODE
,   ltrim(rtrim(ISNULL(CRM_CST_SVC_CODE, '0' )))  AS CRM_CST_SVC_CODE_CALC 
