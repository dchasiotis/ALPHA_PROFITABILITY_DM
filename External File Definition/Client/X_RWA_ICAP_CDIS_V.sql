ALTER VIEW STG.X_RWA_ICAP_CDIS_V
AS
SELECT 

         COUNTERPARTY_ORIGINAL
	   , ISNULL(COALESCE(NULLIF(REPLACE(LTRIM(REPLACE(SUBSTRING(ltrim(rtrim(COUNTERPARTY_ORIGINAL)), 5, LEN(ltrim(rtrim(COUNTERPARTY_ORIGINAL)))-4), '0', ' ')), ' ', '0'),''), '0'), '0' ) AS COUNTERPARTY_ORIGINAL_CALC
	   , Rating
       , ERW
	   , case when ERW='n/a' then 0 else round(convert(float,REPLACE(replace(LTRIM(RTRIM(isnull(ERW,'0'))),'%',''),',','.')),6)/100 end as ERW_calc
	   , case when substring(COUNTERPARTY_ORIGINAL,1,4)='CDI_' THEN 'AB1001' WHEN substring(COUNTERPARTY_ORIGINAL,1,4)='CYC_' THEN 'AB1062'
	   ELSE '' END ENTITY_CODE_CALC



FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_RWA_ICAP_CDIS.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_RWA_ICAP_CDIS_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz


