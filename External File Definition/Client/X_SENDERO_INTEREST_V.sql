alter VIEW STG.X_SENDERO_INTEREST_V
AS
SELECT
	SOURCE_CODE
,   CASE WHEN isnull(SOURCE_CODE,'') = ''  THEN '0' ELSE SOURCE_CODE END  AS SOURCE_CODE_CALC
,	ACCOUNT_CODE
,   CASE WHEN isnull(ACCOUNT_CODE,'') = ''  THEN '0' ELSE ACCOUNT_CODE END  AS ACCOUNT_CODE_CALC
,	BALANCE_TYPE_CODE
,   CASE WHEN isnull(BALANCE_TYPE_CODE,'') = ''  THEN '0' ELSE BALANCE_TYPE_CODE END  AS BALANCE_TYPE_CODE_CALC
,	GL_ACCOUNT_TYPE_CODE
,   CASE WHEN isnull(GL_ACCOUNT_TYPE_CODE,'') = ''  THEN '0' ELSE GL_ACCOUNT_TYPE_CODE END  AS GL_ACCOUNT_TYPE_CODE_CALC
,	CURRENCY_CODE
,   CASE WHEN isnull(CURRENCY_CODE,'') = '' THEN '0' ELSE CURRENCY_CODE END  AS CURRENCY_CODE_CALC
,	EOP_ACCRUED_INTEREST_EUR
,   round(convert(float,REPLACE(replace(LTRIM(RTRIM(isnull(EOP_ACCRUED_INTEREST_EUR,'0'))),'.',''),',','.')),2)  AS EOP_ACCRUED_INTEREST_EUR_CALC
,	REF_MONTH
,   CASE WHEN isnull(REF_MONTH,'') = ''  THEN '-' ELSE REF_MONTH END  AS REF_MONTH_CALC
,	ACCOUNT_CLIENT_CODE
,   ISNULL(COALESCE(NULLIF(REPLACE(LTRIM(REPLACE(ltrim(rtrim(ISNULL(ACCOUNT_CLIENT_CODE,''))), '0', ' ')), ' ', '0'),''), '0'), '0' )  AS ACCOUNT_CLIENT_CODE_CALC
,	SENDERO_ACCOUNT_NUMBER
,   CASE WHEN isnull(SENDERO_ACCOUNT_NUMBER,'') = '' THEN '0' ELSE SENDERO_ACCOUNT_NUMBER END  AS SENDERO_ACCOUNT_NUMBER_CALC
FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_SENDERO_INTEREST.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_SENDERO_INTEREST_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz


