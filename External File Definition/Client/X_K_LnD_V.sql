
CREATE VIEW STG.X_K_LnD_V
AS
SELECT
  DEAL_ID
, rtrim(ltrim(ISNULL(DEAL_ID, '0' )))  AS DEAL_ID_CALC
, COUNTERPARTY_NAME
, COUNTERPARTY_SHORT_NAME
,   DEAL_TYPE
,   FOLDER_SHORT_NAME
,	TRADE_DATE
,   CONVERT(DATE,CASE WHEN LTRIM(RTRIM(REPLACE(isnull(TRADE_DATE,''),'/','-'))) = '' THEN '9999-01-01'   
         ELSE LTRIM(RTRIM(REPLACE(TRADE_DATE,'/','-'))) END,103 ) AS TRADE_DATE_CALC
,   VALUE_DATE
,   CONVERT(DATE,CASE WHEN LTRIM(RTRIM(REPLACE(isnull(VALUE_DATE,''),'/','-'))) = '' THEN '9999-01-01'   
         ELSE LTRIM(RTRIM(REPLACE(VALUE_DATE,'/','-'))) END,103 ) AS VALUE_DATE_CALC
,   MATURITY_DATE
,   CONVERT(DATE,CASE WHEN LTRIM(RTRIM(REPLACE(isnull(MATURITY_DATE,''),'/','-'))) = '' THEN '9999-01-01'   
         ELSE LTRIM(RTRIM(REPLACE(MATURITY_DATE,'/','-'))) END,103 ) AS MATURITY_DATE_CALC
,   CCY
,   PRINCIPAL
,   ROUND(cast(REPLACE(REPLACE(ISNULL(PRINCIPAL,'0'), '.', ''),',', '.') as float) ,2) as PRINCIPAL_CALC
,   VALUE_RATE
,   ROUND(cast(REPLACE(REPLACE(ISNULL(VALUE_RATE,'0'), '.', ''),',', '.') as float) ,6) as VALUE_RATE_CALC
,   CLIENT_MARGIN
,   ROUND(cast(REPLACE(REPLACE(ISNULL(CLIENT_MARGIN,'0'), '.', ''),',', '.') as float) ,6) as CLIENT_MARGIN_CALC
,   PURPOSE
,   COMMENT
FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_K_LnD.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_K_LnD_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz

