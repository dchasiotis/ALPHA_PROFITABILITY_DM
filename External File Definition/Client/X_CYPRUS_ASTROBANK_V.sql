ALTER VIEW STG.X_CYPRUS_ASTROBANK_V
AS
SELECT

  CUSTOMER_NUMBER
, ISNULL(COALESCE(NULLIF(REPLACE(LTRIM(REPLACE(ltrim(rtrim(CUSTOMER_NUMBER)), '0', ' ')), ' ', '0'),''), '0'), '0' )  AS CUSTOMER_NUMBER_CALC  ---- CLIENT_CODE ----
, CUSTOMER_NAME
, case when ltrim(rtrim(isnull(CUSTOMER_NAME,''))) = '' then '-'   ---- CLIENT_NAME ----
  else ltrim(rtrim(CUSTOMER_NAME)) end  AS CUSTOMER_NAME_CALC
, CUSTOMER_TYPE
, CASE WHEN ltrim(rtrim(isnull(CUSTOMER_TYPE,''))) = '' THEN '0' ELSE ltrim(rtrim(LEFT(CUSTOMER_TYPE,3))) END  AS CUSTOMER_TYPE_CALC  --- CLIENT_CL_CATEGORY_CODE ----
, CUSTOMER_TAX_CODE
, case when ltrim(rtrim(isnull(CUSTOMER_TAX_CODE,''))) = '' then '-'   ----- CLIENT_AFM_CODE -----   
   else ltrim(rtrim(CUSTOMER_TAX_CODE)) end  AS CUSTOMER_TAX_CODE_CALC
, ORIGINATING_COUNTRY
, CASE WHEN ltrim(rtrim(isnull(ORIGINATING_COUNTRY,''))) = '' THEN  '0' ELSE ltrim(rtrim(ORIGINATING_COUNTRY)) END   AS ORIGINATING_COUNTRY_CALC  --- ORIG_COUNTRY ---
, ACCOUNT_NUMBER
, ISNULL (CASE WHEN SUBSTRING(ltrim(rtrim(ACCOUNT_NUMBER)),1,2)='2_' THEN REPLACE(LTRIM(REPLACE(ltrim(rtrim(ACCOUNT_NUMBER)), '2_', ' ')), ' ', '0') 
               WHEN SUBSTRING(ltrim(rtrim(ACCOUNT_NUMBER)),1,2)='1_' THEN REPLACE(LTRIM(REPLACE(ltrim(rtrim(ACCOUNT_NUMBER)), '1_', ' ')), ' ', '0') 
		  ELSE LEFT (ltrim(rtrim(ACCOUNT_NUMBER)), LEN (ltrim(rtrim(ACCOUNT_NUMBER)))-1) END , '0')  AS ACCOUNT_NUMBER_CALC   ---- ACCOUNT_CODE ----
, GL_ACCOUNT_TYPE
, CASE WHEN ltrim(rtrim(isnull(GL_ACCOUNT_TYPE,''))) = ''  THEN '0' ELSE ltrim(rtrim(GL_ACCOUNT_TYPE)) END  AS  GL_ACCOUNT_TYPE_CALC  ---- ACCOUNT_GL_ACCOUNT_TYPE_CODE---
, BRANCH_MAINT
, CASE WHEN ltrim(rtrim(isnull(BRANCH_MAINT,''))) = ''  THEN '0' ELSE ltrim(rtrim(BRANCH_MAINT)) END  AS BRANCH_MAINT_CALC   ---- ACCOUNT_BRANCH_CODE ----
, ACCOUNT_STATUS
, CASE WHEN ltrim(rtrim(isnull(ACCOUNT_STATUS,''))) = '' THEN '0' ELSE ltrim(rtrim(ACCOUNT_STATUS)) END  AS ACCOUNT_STATUS_CALC  --- ACCOUNT_STATUS_CODE ---
, PRODUCT_CODE
, CASE WHEN ltrim(rtrim(isnull(PRODUCT_CODE,''))) = '' THEN '0' ELSE ltrim(rtrim(PRODUCT_CODE)) END  AS PRODUCT_CODE_CALC   ---- ACCOUNT_DWH_PRODUCT_CODE ----
, CURRENCY_CODE
, case when ltrim(rtrim(isnull(CURRENCY_CODE,''))) = '' then '-'   ---- ACCOUNT_CURRENCY_ISO ----
  else ltrim(rtrim(CURRENCY_CODE)) end  AS CURRENCY_CODE_CALC
, INTEREST_RATE
,  ROUND(cast(REPLACE(REPLACE(ISNULL(INTEREST_RATE,'0'), '.', ''),',', '.') as float) ,6) as INTEREST_RATE_CALC
, ORIGINAL_BALANCE_EUR
,  ROUND(cast(REPLACE(REPLACE(ISNULL(ORIGINAL_BALANCE_EUR,'0'), '.', ''),',', '.') as float) ,6) as ORIGINAL_BALANCE_EUR_CALC
, ORIGINAL_BALANCE_CCY
,  ROUND(cast(REPLACE(REPLACE(ISNULL(ORIGINAL_BALANCE_CCY,'0'), '.', ''),',', '.') as float) ,6) as ORIGINAL_BALANCE_CCY_CALC
, ORIGINATION_DATE 
,   CASE WHEN ORIGINATION_DATE IS NULL THEN '9999-01-01' ELSE CONVERT(DATE,CASE WHEN LTRIM(RTRIM(REPLACE(isnull(ORIGINATION_DATE,''),'/','-'))) = '' THEN '9999-01-01'   
    ELSE LTRIM(RTRIM(REPLACE(ORIGINATION_DATE,'/','-'))) END,103 ) END AS ORIGINATION_DATE_CALC
, MATURITY_DATE
,   CASE WHEN MATURITY_DATE IS NULL THEN '9999-01-01' ELSE CONVERT(DATE,CASE WHEN LTRIM(RTRIM(REPLACE(isnull(MATURITY_DATE,''),'/','-'))) = '' THEN '9999-01-01'   
    ELSE LTRIM(RTRIM(REPLACE(MATURITY_DATE,'/','-'))) END,103 ) END AS MATURITY_DATE_CALC
, REAL_CLOSE_DATE
,   CASE WHEN REAL_CLOSE_DATE IS NULL THEN '9999-01-01' ELSE CONVERT(DATE,CASE WHEN LTRIM(RTRIM(REPLACE(isnull(REAL_CLOSE_DATE,''),'/','-'))) = '' THEN '9999-01-01'   
    ELSE LTRIM(RTRIM(REPLACE(REAL_CLOSE_DATE,'/','-'))) END,103 ) END AS REAL_CLOSE_DATE_CALC
, PREVIOUS_REPRICE_DATE
,   CASE WHEN PREVIOUS_REPRICE_DATE IS NULL THEN '9999-01-01' ELSE CONVERT(DATE,CASE WHEN LTRIM(RTRIM(REPLACE(isnull(PREVIOUS_REPRICE_DATE,''),'/','-'))) = '' THEN '9999-01-01'   
    ELSE LTRIM(RTRIM(REPLACE(PREVIOUS_REPRICE_DATE,'/','-'))) END,103 ) END AS PREVIOUS_REPRICE_DATE_CALC
, NEXT_REPRICE_DATE
,   CASE WHEN NEXT_REPRICE_DATE IS NULL THEN '9999-01-01' ELSE CONVERT(DATE,CASE WHEN LTRIM(RTRIM(REPLACE(isnull(NEXT_REPRICE_DATE,''),'/','-'))) = '' THEN '9999-01-01'   
    ELSE LTRIM(RTRIM(REPLACE(NEXT_REPRICE_DATE,'/','-'))) END,103 ) END AS NEXT_REPRICE_DATE_CALC
, CURRENT_BOOK_BAL_EUR
,  ROUND(cast(REPLACE(REPLACE(ISNULL(CURRENT_BOOK_BAL_EUR,'0'), '.', ''),',', '.') as float) ,6) as CURRENT_BOOK_BAL_EUR_CALC
, CURRENT_BOOK_BAL_CCY
,  ROUND(cast(REPLACE(REPLACE(ISNULL(CURRENT_BOOK_BAL_CCY,'0'), '.', ''),',', '.') as float) ,6) as CURRENT_BOOK_BAL_CCY_CALC
, AVERAGE_BALANCE_MONTH_EUR
,  ROUND(cast(REPLACE(REPLACE(ISNULL(AVERAGE_BALANCE_MONTH_EUR,'0'), '.', ''),',', '.') as float) ,6) as AVERAGE_BALANCE_MONTH_EUR_CALC
, AVERAGE_BALANCE_MONTH_CCY
,  ROUND(cast(REPLACE(REPLACE(ISNULL(AVERAGE_BALANCE_MONTH_CCY,'0'), '.', ''),',', '.') as float) ,6) as AVERAGE_BALANCE_MONTH_CCY_CALC
, ACCRUED_INTEREST_MONTH_EUR
,  ROUND(cast(REPLACE(REPLACE(ISNULL(ACCRUED_INTEREST_MONTH_EUR,'0'), '.', ''),',', '.') as float) ,6) as ACCRUED_INTEREST_MONTH_EUR_CALC
, CUSTOMER_FLAG_ALPHA_BANK
,  CASE WHEN ltrim(rtrim(isnull(CUSTOMER_FLAG_ALPHA_BANK,''))) = '' THEN '0' ELSE RIGHT('00'+ltrim(rtrim(CUSTOMER_FLAG_ALPHA_BANK)), 2)  END  AS CUSTOMER_FLAG_ALPHA_BANK_CALC  ---- CLIENT_CL_TYPE_CODE ----
, CUSTOMER_FLAG
,  CASE WHEN ltrim(rtrim(ISNULL(CUSTOMER_FLAG,''))) = '' THEN '0' ELSE RIGHT('00'+ltrim(rtrim(CUSTOMER_FLAG)), 2)  END  AS CUSTOMER_FLAG_CALC   --- CLIENT_MONITORING_UNIT_CODE ---
, PAYMENT_TYPE
, CASE WHEN ltrim(rtrim(isnull(PAYMENT_TYPE,''))) = '' THEN '0' ELSE ltrim(rtrim(PAYMENT_TYPE)) END  AS PAYMENT_TYPE_CALC   ---- ACCOUNT_PAYMENT_TYPE_CODE ----
, ACCRUAL_BASIS
, CASE WHEN ltrim(rtrim(isnull(ACCRUAL_BASIS,''))) = '' THEN '0' ELSE ltrim(rtrim(ACCRUAL_BASIS)) END  AS ACCRUAL_BASIS_CALC   ---- ACCOUNT_ACCRUAL_BASIS_CODE ---- 
, RATE_FLAG
, CASE WHEN ltrim(rtrim(isnull(RATE_FLAG,''))) = '' THEN '0' ELSE ltrim(rtrim(RATE_FLAG)) END  AS RATE_FLAG_CALC   ----  ACCOUNT_RATE_TYPE_CODE ----
, LEGAL_ENTITY
, RIGHT(LEGAL_ENTITY,6) AS LEGAL_ENTITY_CALC
, SNAPSHOTDATE
, PRODUCTNAME
, MAPPEDMASTERPRODUCT
, EBA
, MAPPEDPRODUCTLEVEL1
, MAPPEDPRODUCTLEVEL2
, EXCLUDED_FROM_DAILY

FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_CYPRUS_ASTROBANK.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_CYPRUS_ASTROBANK_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz


