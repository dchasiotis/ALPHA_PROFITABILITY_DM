CREATE VIEW STG.X_LONDON_INTEREST_AVG_V
AS
SELECT 
		
   ACCOUNT_NUMBER	
 , CUSTOMER_NUMBER
 , CUSTOMER_NUMBER_CALC
 , GL_ACCOUNT_TYPE 
 , WEIGHTED_INCOME_EUR
 , round(convert(float,REPLACE(LTRIM(RTRIM(isnull(WEIGHTED_INCOME_EUR,0))),',','.')),2)  AS WEIGHTED_INCOME_EUR_CALC
 , AVERAGE_BALANCE_EUR
  , round(convert(float,REPLACE(LTRIM(RTRIM(isnull(AVERAGE_BALANCE_EUR,0))),',','.')),2)  AS AVERAGE_BALANCE_EUR_CALC
 , AVERAGE_BALANCE_CCY
  , round(convert(float,REPLACE(LTRIM(RTRIM(isnull(AVERAGE_BALANCE_CCY,0))),',','.')),2)  AS AVERAGE_BALANCE_CCY_CALC


FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_LONDON_INTEREST_AVG.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_LONDON_INTEREST_AVG_FF.txt',FIRSTROW=2
) as zzz
	