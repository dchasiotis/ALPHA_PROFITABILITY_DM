alter VIEW STG.X_FORWARDS_V
AS
SELECT
	FOLDER
,	DEAL
,	TRADE_DATE
,	CURR1
,	AMOUNT_CUR1
,   ROUND(cast(REPLACE(REPLACE(ISNULL(AMOUNT_CUR1,'0'), '.', ''),',', '.') as float) ,2) as AMOUNT_CUR1_CALC
,	CURR2
,	AMOUNT_CUR2
,	POINTS
,	BLOCK_NUMBER
,	SPOT_RATE
,	CLIENT_POINTS
,	CLIENT_FORWARD_RATE
,	FORWARD_RATE
,	PL
,   ROUND(cast(REPLACE(REPLACE(ISNULL(PL,'0'), '.', ''),',', '.') as float) ,2) as PL_CALC
,	COUNTERPARTY_SHORT_NAME
, case when isnumeric(ltrim(rtrim(COUNTERPARTY_SHORT_NAME))) = 0 then '0'  ------ ACCOUNT_BRANCH_CODE
       when COUNTERPARTY_SHORT_NAME is null then '0'
	   when COUNTERPARTY_SHORT_NAME = '' then '0'
	   else RIGHT('0000'+ltrim(rtrim(COUNTERPARTY_SHORT_NAME)), 4) END  AS COUNTERPARTY_SHORT_NAME_CALC
,	MATURITY_DATE
,	COMMENT
,	DEAL_STATUS
,	TYPE_OF_EVENT
,	DEALID
,   rtrim(ltrim(ISNULL(DEALID, '0' )))  AS DEALID_CALC
,	AFM
,	ADDITIONALCOMMENTS
,	CLIENTCATEGORY
,	CLIENTNAME
,	CLIENTNUMBER
,   rtrim(ltrim(ISNULL(CLIENTNUMBER, '0' )))  AS CLIENTNUMBER_CALC
,	DEALTYPE
,	SENDCONFO
,	VALUEDATE
FROM    OPENROWSET(BULK 'X:/DATA/CLIENT/DATA/X_FORWARDS.csv', FORMATFILE = 'X:/DATA/CLIENT/FF/X_FORWARDS_FF.txt', FIRSTROW=2, CODEPAGE=65001) as zzz



